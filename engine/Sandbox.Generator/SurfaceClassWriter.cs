using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Sandbox.Generator;

/// <summary>
/// Game code's typed class for a Slang surface: written from the surface's description (<c>Sandbox.ShaderCompiler</c>'s
/// <c>MaterialClassWriter.Describe</c>, the reflection the engine's own typed classes come from), which the engine puts in
/// the code archive as <c>.surface</c> files beside the code. The class has the struct's name and a property per field
/// with the field's name, as the engine's classes do, and sets each value on a <c>Sandbox.Material</c> by the name
/// <c>Material.Set</c> takes for it, so <c>new Rock { Tint = … }</c> is checked by the C# compiler while setting values by
/// name keeps working. A description comes from an archive anyone can make: every name is checked to be an identifier
/// (or plain path text) and anything else is left out.
/// </summary>
public static class SurfaceClassWriter
{
	/// <summary>The extension of a surface's description in a code archive.</summary>
	public const string Extension = ".surface";

	/// <summary>The namespace the classes are in, under the project's root namespace.</summary>
	public const string Namespace = "Surfaces";

	sealed class Field
	{
		public string Name, SetName, Kind, Group, Min, Max;
		public int Components;
		public float[] Default;
		public bool Srgb;
	}

	/// <summary>
	/// The class's source for <paramref name="description"/>, in <c>{rootNamespace}.Surfaces</c>; null when it isn't a
	/// description this reads (another version, or no valid type name).
	/// </summary>
	public static string Write( string description, string rootNamespace )
	{
		if ( description is null ) return null;
		var lines = description.Replace( "\r", "" ).Split( '\n' );
		if ( lines.Length == 0 || lines[0] != "sbox-surface\t1" ) return null;

		string type = null, shader = null, file = null;
		var fields = new List<Field>();
		foreach ( var line in lines.Skip( 1 ) )
		{
			var parts = line.Split( '\t' );
			switch ( parts[0] )
			{
				case "type" when parts.Length > 1: type = parts[1]; break;
				case "shader" when parts.Length > 1: shader = parts[1]; break;
				case "file" when parts.Length > 1: file = parts[1]; break;
				case "field" when parts.Length >= 10:
					if ( !int.TryParse( parts[4], NumberStyles.Integer, CultureInfo.InvariantCulture, out var components ) ) continue;
					fields.Add( new Field
					{
						Name = parts[1],
						SetName = parts[2],
						Kind = parts[3],
						Components = components,
						Default = parts[5].Length == 0 ? null : parts[5].Split( ',' ).Select( v => float.TryParse( v, NumberStyles.Float, CultureInfo.InvariantCulture, out var f ) ? f : 0 ).ToArray(),
						Group = parts[6],
						Min = parts[7],
						Max = parts[8],
						Srgb = parts[9] == "srgb",
					} );
					break;
			}
		}

		if ( !IsIdentifier( type ) || !IsPlainText( shader ) ) return null;
		var ns = string.IsNullOrEmpty( rootNamespace ) || !rootNamespace.Split( '.' ).All( IsIdentifier ) ? Namespace : $"{rootNamespace}.{Namespace}";

		var s = new StringBuilder();
		s.Append( "// <auto-generated/>\n" );
		s.Append( "// Generated by Sandbox.Generator from " ).Append( IsPlainText( file ) ? file : shader ).Append( "'s description; it changes with the shader.\n" );
		s.Append( "#nullable disable\n\n" );
		s.Append( "namespace " ).Append( ns ).Append( "\n{\n" );
		s.Append( "\t/// <summary>\n" );
		s.Append( "\t/// The surface <c>" ).Append( type ).Append( "</c> (<c>" ).Append( Xml( shader ) ).Append( "</c>): a material of it, with a property per\n" );
		s.Append( "\t/// field, set on the material by name. A property reads back what was set through this object, or the field's default.\n" );
		s.Append( "\t/// </summary>\n" );
		s.Append( "\tpublic sealed partial class " ).Append( type ).Append( "\n\t{\n" );
		s.Append( "\t\t/// <summary>The shader its materials name.</summary>\n" );
		s.Append( "\t\tpublic const string ShaderPath = " ).Append( Literal( shader ) ).Append( ";\n\n" );
		s.Append( "\t\t/// <summary>The material its properties set values on.</summary>\n" );
		s.Append( "\t\tpublic global::Sandbox.Material Material { get; }\n\n" );
		s.Append( "\t\t/// <summary>A new material of the surface, every field at its default.</summary>\n" );
		s.Append( "\t\tpublic " ).Append( type ).Append( "() : this( global::Sandbox.Material.Create( " ).Append( Literal( type.ToLowerInvariant() ) ).Append( ", ShaderPath ) )\n\t\t{\n\t\t}\n\n" );
		s.Append( "\t\t/// <summary>The surface's properties on <paramref name=\"material\"/>, a material of it.</summary>\n" );
		s.Append( "\t\tpublic " ).Append( type ).Append( "( global::Sandbox.Material material )\n\t\t{\n\t\t\tMaterial = material;\n\t\t}\n\n" );
		s.Append( "\t\t/// <summary>The material, for anything that takes one.</summary>\n" );
		s.Append( "\t\tpublic static implicit operator global::Sandbox.Material( " ).Append( type ).Append( " surface ) => surface?.Material;\n" );

		var used = new HashSet<string>( StringComparer.Ordinal ) { type, "ShaderPath", "Material" };
		foreach ( var field in fields )
		{
			if ( !IsIdentifier( field.Name ) || !used.Add( field.Name ) || !IsPlainText( field.SetName ) ) continue;
			if ( TypeOf( field ) is not { } csType ) continue;

			var notes = new List<string>();
			if ( IsPlainText( field.Group ) && field.Group.Length > 0 ) notes.Add( $"group \"{Xml( field.Group )}\"" );
			if ( IsNumber( field.Min ) || IsNumber( field.Max ) ) notes.Add( $"range {(IsNumber( field.Min ) ? field.Min : "0")} to {(IsNumber( field.Max ) ? field.Max : "0")}" );
			if ( field.Srgb ) notes.Add( "sRGB" );

			var backing = "_" + char.ToLowerInvariant( field.Name[0] ) + field.Name.Substring( 1 ) + "_";
			s.Append( '\n' );
			s.Append( "\t\t" ).Append( csType ).Append( ' ' ).Append( backing );
			if ( DefaultOf( field ) is { } value ) s.Append( " = " ).Append( value );
			s.Append( ";\n\n" );
			s.Append( "\t\t/// <summary><c>" ).Append( field.Name ).Append( "</c>" ).Append( notes.Count > 0 ? ": " + string.Join( ", ", notes ) : "" ).Append( ".</summary>\n" );
			s.Append( "\t\tpublic " ).Append( csType ).Append( ' ' ).Append( field.Name ).Append( "\n\t\t{\n" );
			s.Append( "\t\t\tget => " ).Append( backing ).Append( ";\n" );
			s.Append( "\t\t\tset\n\t\t\t{\n\t\t\t\t" ).Append( backing ).Append( " = value;\n" );
			s.Append( "\t\t\t\tMaterial?.Set( " ).Append( Literal( field.SetName ) ).Append( ", value );\n" );
			s.Append( "\t\t\t}\n\t\t}\n" );
		}

		s.Append( "\t}\n}\n" );
		return s.ToString();
	}

	/// <summary>The C# type a field reads and writes as, as the engine's classes have it; null where there's none.</summary>
	static string TypeOf( Field field ) => (field.Kind, field.Components) switch
	{
		("float", 1 ) => "float",
		("float", 2 ) => "global::Vector2",
		("float", 3 ) => "global::Vector3",
		("float", 4 ) => "global::Vector4",
		("int", 1 ) => "int",
		("uint", 1 ) => "int",
		("bool", 1 ) => "bool",
		("texture", _ ) => "global::Sandbox.Texture",
		_ => null,
	};

	static string DefaultOf( Field field )
	{
		if ( field.Default is null || field.Kind == "texture" ) return null;
		string At( int i ) => Number( i < field.Default.Length ? field.Default[i] : 0 );
		return (field.Kind, field.Components) switch
		{
			("float", 1 ) => At( 0 ),
			("float", 2 ) => $"new global::Vector2( {At( 0 )}, {At( 1 )} )",
			("float", 3 ) => $"new global::Vector3( {At( 0 )}, {At( 1 )}, {At( 2 )} )",
			("float", 4 ) => $"new global::Vector4( {At( 0 )}, {At( 1 )}, {At( 2 )}, {At( 3 )} )",
			("bool", _ ) => field.Default.Length > 0 && field.Default[0] != 0 ? "true" : "false",
			_ => ((int)(field.Default.Length > 0 ? field.Default[0] : 0)).ToString( CultureInfo.InvariantCulture ),
		};
	}

	static string Number( float value )
	{
		if ( float.IsNaN( value ) || float.IsInfinity( value ) ) value = 0;
		var text = value.ToString( "R", CultureInfo.InvariantCulture );
		return (text.Contains( "." ) || text.Contains( "E" ) ? text : text + ".0") + "f";
	}

	static bool IsNumber( string text ) => !string.IsNullOrEmpty( text ) && float.TryParse( text, NumberStyles.Float, CultureInfo.InvariantCulture, out var f ) && !float.IsNaN( f ) && !float.IsInfinity( f );

	/// <summary>A C# identifier of letters, digits and underscores, not starting with a digit, and not a keyword.</summary>
	static bool IsIdentifier( string text ) =>
		!string.IsNullOrEmpty( text ) && text.Length <= 128 && (char.IsLetter( text[0] ) || text[0] == '_') && text.All( c => c < 128 && (char.IsLetterOrDigit( c ) || c == '_') )
		&& Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind( text ) == Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
		&& Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetContextualKeywordKind( text ) == Microsoft.CodeAnalysis.CSharp.SyntaxKind.None;

	/// <summary>Printable ASCII with no quotes, backslashes or angle brackets: safe in a string literal and a doc comment as it is.</summary>
	static bool IsPlainText( string text ) =>
		text is not null && text.Length <= 260 && text.All( c => c >= 32 && c < 127 && c != '"' && c != '\\' && c != '<' && c != '>' && c != '&' );

	static string Literal( string text ) => "\"" + text + "\"";

	static string Xml( string text ) => text;
}
