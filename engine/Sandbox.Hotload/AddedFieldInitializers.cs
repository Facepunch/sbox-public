using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;

namespace Sandbox
{
	partial class Hotload
	{
		/// <summary>
		/// How to initialize a field added by this hotload, found from its <see cref="AddedFieldInitializerAttribute"/> method.
		/// </summary>
		private sealed class AddedFieldInitializer
		{
			/// <summary>
			/// Returns the initializer's value, or null if the field has no initializer we can evaluate.
			/// </summary>
			public MethodInfo Method;

			/// <summary>
			/// The initializer may throw for every instance, so we only log the first.
			/// </summary>
			public bool HasLoggedThrow;
		}

		private readonly Dictionary<FieldInfo, AddedFieldInitializer> AddedFieldInitializers = new();

		private void ClearFieldDefaults()
		{
			AddedFieldInitializers.Clear();
		}

		/// <summary>
		/// True if <paramref name="member"/> was generated by the compiler to initialize an added field. These
		/// only exist for the compile that adds their field, so shouldn't count as a change to their type.
		/// </summary>
		internal static bool IsAddedFieldInitializer( MemberInfo member )
		{
			return member is MethodInfo method && method.IsDefined( typeof( AddedFieldInitializerAttribute ), false );
		}

		/// <summary>
		/// Attempts to get the value of the initializer of a field that has been added to an existing type, so it
		/// can be set on existing instances. Returns true if successful.
		/// </summary>
		/// <remarks>
		/// The compiler generates a method for each added field with an initializer that returns its value, marked
		/// with <see cref="AddedFieldInitializerAttribute"/>. The value isn't cached, but evaluated for each instance.
		/// </remarks>
		/// <param name="field">Field to retrieve a default value for.</param>
		/// <param name="value">If successful, contains the default value.</param>
		private bool TryGetDefaultValue( FieldInfo field, out object value )
		{
			value = null;

			if ( !AddedFieldInitializers.TryGetValue( field, out var initializer ) )
			{
				AddedFieldInitializers[field] = initializer = new AddedFieldInitializer { Method = FindAddedFieldInitializer( field ) };
			}

			if ( initializer.Method is null ) return false;

			try
			{
				value = initializer.Method.Invoke( null, null );
				return true;
			}
			catch ( TargetInvocationException e ) when ( e.InnerException is not null )
			{
				if ( !initializer.HasLoggedThrow )
				{
					initializer.HasLoggedThrow = true;
					Log( e.InnerException, $"Initializer of added field threw an exception, so it keeps its default value.", field );
				}

				return false;
			}
		}

		private MethodInfo FindAddedFieldInitializer( FieldInfo field )
		{
			const BindingFlags flags = BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly;

			// Search the field's declaring type, which is the constructed type for generics, so the method is too

			var match = field.DeclaringType!.GetMethods( flags )
				.Select( x => (Method: x, Attribute: x.GetCustomAttribute<AddedFieldInitializerAttribute>()) )
				.FirstOrDefault( x => x.Attribute?.FieldName == field.Name );

			if ( match.Attribute is null )
			{
				// No initializer, so the default value is correct

				return null;
			}

			if ( !match.Attribute.Supported )
			{
				Log( HotloadEntryType.Warning, $"Initializer of added field couldn't be evaluated outside a constructor, for example because it uses a constructor parameter. Existing instances keep its default value.", field );
				return null;
			}

			return match.Method;
		}
	}
}
