namespace Sandbox;

/// <summary>
/// Default normalized appearance values used by clothing containers and dressers.
/// </summary>
internal static class AvatarDefaults
{
	/// <summary>
	/// Default position on the eye colour gradient, using Citizen's brown.
	/// </summary>
	public const float EyeColor = 0.0f;

	/// <summary>
	/// Default horizontal iris alignment. The midpoint preserves the material's centre.
	/// </summary>
	public const float EyeAlign = 0.5f;

	/// <summary>
	/// Default neck size, on the zero-to-one slider range.
	/// </summary>
	public const float NeckSize = 0.0f;

	/// <summary>
	/// Default waist size, on the zero-to-one slider range.
	/// </summary>
	public const float WaistSize = 0.5f;

	/// <summary>
	/// Default chest size, on the zero-to-one slider range.
	/// </summary>
	public const float ChestSize = 0.5f;

	/// <summary>
	/// Default head shape, on the zero-to-one slider range.
	/// </summary>
	public const float HeadShape = 0.5f;

	/// <summary>
	/// Default nose size, on the zero-to-one slider range.
	/// </summary>
	public const float NoseSize = 0.0f;

	/// <summary>
	/// Default chin size, on the zero-to-one slider range.
	/// </summary>
	public const float ChinSize = 0.0f;
}
