using System;
using System.IO;
using System.Text;

namespace Editor;

/// <summary>
/// Connect project-local agent instructions to the installed engine's automation tools.
/// </summary>
internal static class ProjectAgentInstructions
{
	const string GuidePath = ".sbox/agent-guide.md";
	const string Marker = "<!-- sbox:agent-guide -->";

	const string ProjectInstructions = """
		<!-- sbox:agent-guide -->
		## s&box tooling

		Read [.sbox/agent-guide.md](.sbox/agent-guide.md) for this project's installed engine,
		CLI, API reference paths and editing workflow. The editor refreshes that local guide
		when the project opens. Project-specific instructions in this file still apply.

		If the guide is missing after cloning, locate the engine using `FACEPUNCH_ENGINE`
		(on Windows, also check the user environment variable), or ask for its installation path.
		Run `bin/managed/sbox-cli.exe --help` from that installation and read the guide it names.
		Opening this project's `.sbproj` in the editor recreates the local guide.
		""";

	/// <summary>
	/// Refresh local installation details and append a discovery link without replacing author instructions.
	/// Failures must not prevent creating or opening the project.
	/// </summary>
	internal static void Update( string configPath, string enginePath, Sandbox.DataModel.ProjectAISettings settings )
	{
		if ( settings?.WriteAgentInstructions == false )
			return;

		try
		{
			configPath = Path.GetFullPath( configPath );
			enginePath = Path.GetFullPath( enginePath );
			var projectPath = Path.GetDirectoryName( configPath );
			var guidePath = Path.Combine( projectPath, GuidePath );
			var guide = CreateGuide( configPath, enginePath );

			Directory.CreateDirectory( Path.GetDirectoryName( guidePath ) );
			if ( !File.Exists( guidePath ) || File.ReadAllText( guidePath ) != guide )
			{
				File.WriteAllText( guidePath, guide );
			}

			AppendProjectInstructions( Path.Combine( projectPath, "AGENTS.md" ) );
		}
		catch ( Exception e ) when ( e is IOException or UnauthorizedAccessException )
		{
			Log.Warning( $"Couldn't update agent instructions for {configPath}: {e.Message}" );
		}
	}

	/// <summary>
	/// Add the stable link once, preserving existing bytes, encoding and line endings.
	/// </summary>
	static void AppendProjectInstructions( string path )
	{
		using var stream = new FileStream( path, FileMode.OpenOrCreate, FileAccess.ReadWrite, FileShare.Read );
		using var reader = new StreamReader( stream, new UTF8Encoding( false ), detectEncodingFromByteOrderMarks: true, leaveOpen: true );
		var content = reader.ReadToEnd();

		if ( content.Contains( Marker, StringComparison.Ordinal ) || content.Contains( GuidePath, StringComparison.Ordinal ) )
			return;

		var newline = content.Contains( "\r\n", StringComparison.Ordinal ) ? "\r\n" : "\n";
		var prefix = content.Length == 0 ? "# Project instructions" + newline + newline : newline + newline;
		var instructions = ProjectInstructions.Replace( "\r\n", "\n" ).Replace( "\n", newline );

		stream.Seek( 0, SeekOrigin.End );
		using var writer = new StreamWriter( stream, reader.CurrentEncoding, leaveOpen: true );
		writer.Write( prefix + instructions + newline );
	}

	/// <summary>
	/// Keep machine-specific paths in the project's existing ignored .sbox directory.
	/// </summary>
	static string CreateGuide( string configPath, string enginePath )
	{
		var managedPath = Path.Combine( enginePath, "bin", "managed" ).Replace( '\\', '/' );

		return $$"""
			# s&box project guide

			Generated by the s&box editor. This file is local to this installation and refreshed
			when the project opens. Put project-specific instructions in the root AGENTS.md.
			Manage automatic writing and MCP communication in Project Settings > AI.

			## Installation and references

			- Project file: `{{configPath.Replace( '\\', '/' )}}`
			- Engine directory: `{{enginePath.Replace( '\\', '/' )}}`
			- CLI: `{{managedPath}}/sbox-cli.exe`
			- CLI usage guide: `{{managedPath}}/sbox-cli.md`
			- Engine API reference: `{{managedPath}}/Sandbox.Engine.xml`
			- Editor API reference: `{{managedPath}}/Sandbox.Tools.xml`

			Read the CLI usage guide before connecting. Use the installed API references and
			existing project code to check APIs rather than assuming Unity or another engine's API.
			The .NET CLI can also be invoked as `dotnet sbox-cli.dll` from the managed directory;
			launching owned editor/game instances currently requires Windows.

			## Connect and inspect

			1. Run the CLI with `--list` and find the instance matching the project file above.
			2. Use `--connect <pid>` for that instance. If none is running, use `--project <project-file>`
			   to open a visible editor. Keep the connection's stdin open for the whole session.
			3. Follow the guide's MCP initialization sequence, then call `editor_status`. Confirm
			   the project and scene before making changes. Discover available tools with `search_tools`.

			The CLI uses newline-delimited JSON-RPC, not raw C# or shell commands. Initialization
			returns instance-specific instructions and a temporary file exchange directory.
			Use `run_csharp` for code executed inside the editor; consult its discovered schema.

			## Project layout and validation

			- The `.sbproj` file defines the project. `Code/` contains runtime C#; `Editor/` contains
			  editor extensions. `Assets/` holds scenes, prefabs, materials and other resources.
			- `ProjectSettings/` contains project configuration. `.sbox/` holds generated local data.
			  The solution and `.csproj` files are generated by the editor; edit source and `.sbproj`
			  settings instead of hand-editing generated project files.
			- Saving C# triggers editor compilation and hotload. Check `editor_status` until compilation
			  finishes, then check `LastCompileSucceeded` and use `read_console` to inspect failures.
			- Validate behavior in the editor after compilation. Use play mode when the task requires
			  runtime validation. Keep the editor visible. The edited scene and runtime scene can differ.
			- Prefer discovered scene-editing tools and check their undo behavior. C# scripts can mutate
			  live state without undo. Wait for responses and inspect state before retrying a failed mutation.
			- Close stdin when finished. An attached editor stays open; an editor launched by this CLI
			  exits with it. Copy wanted files out of the session exchange directory before cleaning it up.
			""" + "\n";
	}
}
