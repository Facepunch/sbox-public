namespace Sandbox.UI;

/// <summary>
/// Controls whether the font's optical size follows the text size.
/// </summary>
public enum FontOpticalSizing
{
	/// <summary>
	/// Use the text size for the optical size axis.
	/// </summary>
	Auto,

	/// <summary>
	/// Use the font's own optical size unless explicitly overridden.
	/// </summary>
	None
}
