using System.IO;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text;

namespace Sandbox.ShaderCompiler;

/// <summary>
/// What the record definitions (<see cref="RecordDefinitions"/>) make: the C# structs the engine writes records with, and
/// the HLSL header of sizes and byte offsets shaders read them at (both the Slang modules and the HLSL vfx compiles).
/// Both carry the definitions' hash. See docs/reference/borealis-records.md.
/// </summary>
public static class RecordWriter
{
	/// <summary>Where the C# structs go, relative to the engine folder.</summary>
	public const string CSharpFile = "Borealis.Backend/Records.g.cs";

	/// <summary>Where the HLSL header goes, relative to the core shaders.</summary>
	public const string HlslFile = "sbox/record_offsets.slangh";

	/// <summary>The C# structs, internal, in <paramref name="namespace"/>, with <c>\n</c> line ends.</summary>
	public static string CSharp( RecordDefinitions definitions, string @namespace )
	{
		var s = new StringBuilder();
		s.Append( "// <auto-generated/>\n" );
		s.Append( "// Generated by Sandbox.ShaderCompiler from game/core/shaders/" ).Append( RecordDefinitions.File ).Append( " (ShaderCompiler -records, or build-shaders); regenerate it, don't edit it.\n" );
		s.Append( "#nullable disable\n\n" );
		s.Append( "using System.Diagnostics.CodeAnalysis;\nusing System.Runtime.InteropServices;\n\n" );
		s.Append( "namespace " ).Append( @namespace ).Append( ";\n\n" );
		s.Append( "/// <summary>The record definitions these structs were generated from: the hash of " ).Append( RecordDefinitions.File ).Append( ".</summary>\n" );
		s.Append( "internal static class RecordDefinitionsHash\n{\n\tpublic const string Value = \"" ).Append( definitions.Hash ).Append( "\";\n}\n" );

		foreach ( var record in definitions.Records )
		{
			s.Append( '\n' );
			Summary( s, "", record.Summary ?? $"The record {record.Name}." );
			s.Append( "[StructLayout( LayoutKind.Sequential, Pack = 4 )]\n" );
			s.Append( "internal partial struct " ).Append( record.Name ).Append( "\n{\n" );
			s.Append( "\t/// <summary>Bytes of one record.</summary>\n" );
			s.Append( "\tpublic const int Size = " ).Append( record.Size ).Append( ";\n" );
			foreach ( var field in record.Fields )
			{
				s.Append( "\n" );
				s.Append( "\t/// <summary>Byte offset of <see cref=\"" ).Append( field.Name ).Append( "\"/> in the record.</summary>\n" );
				s.Append( "\tpublic const int " ).Append( field.Name ).Append( "Offset = " ).Append( field.Offset ).Append( ";\n" );
				if ( field.ArrayLength > 0 )
				{
					s.Append( "\t/// <summary>Bytes from one element of <see cref=\"" ).Append( field.Name ).Append( "\"/> to the next.</summary>\n" );
					s.Append( "\tpublic const int " ).Append( field.Name ).Append( "Stride = " ).Append( field.Stride ).Append( ";\n" );
					s.Append( "\t/// <summary>Elements of <see cref=\"" ).Append( field.Name ).Append( "\"/>.</summary>\n" );
					s.Append( "\tpublic const int " ).Append( field.Name ).Append( "Length = " ).Append( field.ArrayLength ).Append( ";\n" );
					for ( int i = 0; i < field.ArrayLength; i++ )
					{
						s.Append( "\t/// <summary>Element " ).Append( i ).Append( " of <see cref=\"" ).Append( field.Name ).Append( "\"/>.</summary>\n" );
						s.Append( "\tpublic " ).Append( CSharpType( field ) ).Append( ' ' ).Append( field.Name ).Append( i ).Append( ";\n" );
					}

					Summary( s, "\t", field.Summary );
					s.Append( "\t[UnscopedRef] public Span<" ).Append( CSharpType( field ) ).Append( "> " ).Append( field.Name ).Append( " => MemoryMarshal.CreateSpan( ref " ).Append( field.Name ).Append( "0, " ).Append( field.ArrayLength ).Append( " );\n" );
				}
				else
				{
					Summary( s, "\t", field.Summary );
					s.Append( "\tpublic " ).Append( CSharpType( field ) ).Append( ' ' ).Append( field.Name ).Append( ";\n" );
				}
			}

			s.Append( "}\n" );
		}

		return s.ToString();
	}

	/// <summary>The HLSL header: each record's size, and each field's byte offset (an array's also its stride), as macros.</summary>
	public static string Hlsl( RecordDefinitions definitions )
	{
		var s = new StringBuilder();
		s.Append( "// Generated by Sandbox.ShaderCompiler from " ).Append( RecordDefinitions.File ).Append( " (ShaderCompiler -records, or build-shaders); regenerate it, don't edit it.\n" );
		s.Append( "// Each record's size and its fields' byte offsets, for shaders that read and write records a word or a few at a time.\n" );
		s.Append( "// Definitions hash " ).Append( definitions.Hash ).Append( ".\n" );
		s.Append( "#ifndef SBOX_RECORD_OFFSETS_SLANGH\n#define SBOX_RECORD_OFFSETS_SLANGH\n" );
		foreach ( var record in definitions.Records )
		{
			s.Append( '\n' );
			s.Append( "// " ).Append( record.Name );
			if ( record.Summary is not null ) s.Append( ": " ).Append( record.Summary );
			s.Append( '\n' );
			s.Append( "#define " ).Append( record.Name ).Append( "_Size " ).Append( record.Size ).Append( '\n' );
			foreach ( var field in record.Fields )
			{
				s.Append( "#define " ).Append( record.Name ).Append( '_' ).Append( field.Name ).Append( ' ' ).Append( field.Offset ).Append( '\n' );
				if ( field.ArrayLength > 0 ) s.Append( "#define " ).Append( record.Name ).Append( '_' ).Append( field.Name ).Append( "Stride " ).Append( field.Stride ).Append( '\n' );
			}
		}

		s.Append( "\n#endif\n" );
		return s.ToString();
	}

	/// <summary>
	/// Where a C# struct and a record disagree: its size, a field (an array's elements by name and index) missing, at
	/// another offset, of another size or kind, a field the record doesn't have, or an offset or size constant that isn't
	/// the record's. Empty when they agree.
	/// </summary>
	public static List<string> Compare( RecordLayout record, Type type )
	{
		var problems = new List<string>();
		var size = Marshal.SizeOf( type );
		if ( size != record.Size ) problems.Add( $"{type.Name} is {size} bytes, the record {record.Name} {record.Size}" );
		Constant( problems, type, "Size", record.Size );

		var fields = type.GetFields( BindingFlags.Public | BindingFlags.Instance );
		var expected = new HashSet<string>();
		foreach ( var field in record.Fields )
		{
			Constant( problems, type, field.Name + "Offset", field.Offset );
			if ( field.ArrayLength > 0 ) Constant( problems, type, field.Name + "Stride", field.Stride );

			for ( int i = 0; i < Math.Max( field.ArrayLength, 1 ); i++ )
			{
				var name = field.ArrayLength > 0 ? field.Name + i : field.Name;
				expected.Add( name );
				var member = Array.Find( fields, f => f.Name == name );
				if ( member is null )
				{
					problems.Add( $"{record.Name}.{name} has no field in {type.Name}" );
					continue;
				}

				var offset = (int)Marshal.OffsetOf( type, name );
				var at = field.Offset + i * field.Stride;
				if ( offset != at ) problems.Add( $"{record.Name}.{name} is at {at}, {type.Name}.{name} at {offset}" );
				var bytes = Marshal.SizeOf( member.FieldType );
				if ( bytes != field.Stride ) problems.Add( $"{record.Name}.{name} is {field.Stride} bytes, {type.Name}.{name} {bytes}" );
				if ( field.Struct is not null && member.FieldType.Name != field.Struct ) problems.Add( $"{record.Name}.{name} is a {field.Struct}, {type.Name}.{name} a {member.FieldType.Name}" );
				else if ( Kind( member.FieldType ) is { } kind && kind != field.Kind ) problems.Add( $"{record.Name}.{name} is {field.Kind}, {type.Name}.{name} {kind}" );
			}
		}

		foreach ( var field in fields )
		{
			if ( !expected.Contains( field.Name ) ) problems.Add( $"{type.Name}.{field.Name} isn't in the record {record.Name}" );
		}

		return problems;
	}

	static void Constant( List<string> problems, Type type, string name, int value )
	{
		var constant = type.GetField( name, BindingFlags.Public | BindingFlags.Static );
		if ( constant is null || !constant.IsLiteral ) problems.Add( $"{type.Name}.{name} is missing" );
		else if ( constant.GetRawConstantValue() is int actual && actual != value ) problems.Add( $"{type.Name}.{name} is {actual}, the record's {value}" );
	}

	static RecordFieldKind? Kind( Type type )
	{
		if ( type == typeof( float ) || type == typeof( System.Numerics.Vector2 ) || type == typeof( System.Numerics.Vector3 ) || type == typeof( System.Numerics.Vector4 ) ) return RecordFieldKind.Float;
		if ( type == typeof( int ) ) return RecordFieldKind.Int;
		if ( type == typeof( uint ) ) return RecordFieldKind.UInt;
		return null;
	}

	/// <summary>
	/// Write the C# structs into <paramref name="engine"/> (the engine folder, when it's there) and the HLSL header into
	/// <paramref name="shaders"/> where they aren't what <paramref name="definitions"/> make; the files written.
	/// </summary>
	public static List<string> Update( RecordDefinitions definitions, string engine, string shaders )
	{
		var written = new List<string>();
		void Put( string path, string text )
		{
			text = text.Replace( "\n", "\r\n", StringComparison.Ordinal );
			if ( File.Exists( path ) && File.ReadAllText( path ) == text ) return;
			File.WriteAllText( path, text );
			written.Add( path );
		}

		Put( Path.Combine( shaders, HlslFile ), Hlsl( definitions ) );
		if ( engine is not null && Directory.Exists( Path.Combine( engine, "Borealis.Backend" ) ) ) Put( Path.Combine( engine, CSharpFile ), CSharp( definitions, "Borealis.Backend" ) );
		return written;
	}

	static string CSharpType( RecordField field ) => (field.Kind, field.Components) switch
	{
		(RecordFieldKind.Record, _ ) => field.Struct,
		(RecordFieldKind.Float, 1 ) => "float",
		(RecordFieldKind.Float, 2 ) => "System.Numerics.Vector2",
		(RecordFieldKind.Float, 3 ) => "System.Numerics.Vector3",
		(RecordFieldKind.Float, 4 ) => "System.Numerics.Vector4",
		(RecordFieldKind.Int, 1 ) => "int",
		(RecordFieldKind.UInt, 1 ) => "uint",
		_ => throw new NotSupportedException( $"{field.Name}: a record's int and uint vectors aren't written in C# yet; split it into scalars" ),
	};

	static void Summary( StringBuilder s, string indent, string text )
	{
		if ( text is null ) return;
		s.Append( indent ).Append( "/// <summary>" ).Append( text.Replace( "&", "&amp;", StringComparison.Ordinal ).Replace( "<", "&lt;", StringComparison.Ordinal ).Replace( ">", "&gt;", StringComparison.Ordinal ) ).Append( "</summary>\n" );
	}
}
