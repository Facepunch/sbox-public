using System.Globalization;
using System.IO;
using System.Text;

namespace Sandbox.ShaderCompiler;

/// <summary>
/// The typed C# class for a compiled material: one property per <c>[Material]</c> field, reading and writing its record
/// at the field's offset, so <c>new Rock { Color = texture, Tint = ... }</c> is checked by the C# compiler. The class
/// derives from Borealis.Backend's <c>SurfaceMaterial</c>, which writes the record and draws it.
/// </summary>
public static class MaterialClassWriter
{
	/// <summary>The class's source, in <paramref name="namespace"/>.</summary>
	public static string Write( CompiledShader shader, string @namespace )
	{
		var layout = shader.Material;
		var file = Path.GetFileName( shader.Path );
		var s = new StringBuilder();
		s.Append( "// <auto-generated/>\n" );
		s.Append( "// Generated by Sandbox.ShaderCompiler from " ).Append( file ).Append( "; regenerate it, don't edit it.\n" );
		s.Append( "#nullable disable\n\n" );
		s.Append( "namespace " ).Append( @namespace ).Append( ";\n\n" );
		s.Append( "/// <summary>The material <c>" ).Append( layout.Type ).Append( "</c> (" ).Append( file ).Append( ", " ).Append( shader.Tier == ShaderTier.Surface ? "a surface" : "a raw module" ).Append( ").</summary>\n" );
		s.Append( "public sealed class " ).Append( layout.Type ).Append( " : global::Borealis.Backend.SurfaceMaterial\n{\n" );
		var states = layout.States();
		var hasStates = states.Fields.Count > 0 || states.Defaults != SurfaceRenderDefaults.None;
		if ( hasStates )
		{
			s.Append( "\t/// <summary>Its render state: the struct's attributes and the fields that change it.</summary>\n" );
			s.Append( "\tstatic readonly global::Sandbox.ShaderCompiler.SurfaceStateLayout RenderStates = " ).Append( StatesLiteral( states ) ).Append( ";\n\n" );
		}

		s.Append( "\t/// <summary>A material with every field at its default.</summary>\n" );
		s.Append( "\tpublic " ).Append( layout.Type ).Append( "() : base( \"" ).Append( file ).Append( "\", " ).Append( layout.Size ).Append( ", 0x" ).Append( Hash( layout ).ToString( "X8", CultureInfo.InvariantCulture ) ).Append( 'u' )
			.Append( hasStates ? ", RenderStates" : "" ).Append( " )\n\t{\n" );
		foreach ( var field in layout.Fields )
		{
			if ( field.IsTexture || field.Default is null ) continue;
			s.Append( "\t\t" ).Append( field.Name ).Append( " = " ).Append( Literal( field, field.Default ) ).Append( ";\n" );
		}

		s.Append( "\t}\n" );

		foreach ( var field in layout.Fields )
		{
			s.Append( '\n' );
			var notes = new List<string>();
			if ( field.Group is not null ) notes.Add( $"group \"{field.Group}\"" );
			if ( field.Min is not null || field.Max is not null ) notes.Add( $"range {(field.Min ?? 0).ToString( CultureInfo.InvariantCulture )} to {(field.Max ?? 0).ToString( CultureInfo.InvariantCulture )}" );
			if ( field.Srgb ) notes.Add( "sRGB" );
			if ( field.Opacity ) notes.Add( "opacity" );
			if ( field.RenderStates is { Count: > 0 } rules ) notes.Add( $"render state {string.Join( ", ", rules.Select( r => r.State ) )}" );
			s.Append( "\t/// <summary><c>" ).Append( field.Name ).Append( "</c>" ).Append( notes.Count > 0 ? ": " + string.Join( ", ", notes ) : "" ).Append( ".</summary>\n" );
			var (type, get, set) = Accessors( field );

			// A field that is a blend mode itself reads and writes as one
			if ( field.RenderStates is [{ State: SurfaceStateKind.Blend, Values: null }] && field.Kind is MaterialFieldKind.Int or MaterialFieldKind.UInt )
				(type, get, set) = ("global::Sandbox.ShaderCompiler.SurfaceBlend", $"(global::Sandbox.ShaderCompiler.SurfaceBlend)GetInt( {field.Offset} )", $"SetInt( {field.Offset}, (int)value )");
			s.Append( "\tpublic " ).Append( type ).Append( ' ' ).Append( field.Name ).Append( " { get => " ).Append( get ).Append( "; set => " ).Append( set ).Append( "; }\n" );
		}

		s.Append( "}\n" );
		return s.ToString();
	}

	/// <summary>The first line of <see cref="Describe"/>'s text, with its version.</summary>
	public const string DescriptionHeader = "sbox-surface\t1";

	/// <summary>
	/// A surface's or raw module's material, as game code's typed class is generated from it (Sandbox.Generator's
	/// <c>SurfaceClassWriter</c>, when game code compiles): the same reflection <see cref="Write"/> reads, as tab-separated
	/// lines. <c>type</c> (the struct's name: the class's), <c>shader</c> (what its materials name, <paramref name="shader"/>),
	/// then a <c>field</c> line per field: its name (the property's), the name <c>Material.Set</c> takes for it (its
	/// <c>[Source]</c>, else its name), kind, components, default values, group, range and whether it's sRGB. Fields
	/// <c>Material.Set</c> can't reach (a <c>[Source( "Shader: … " )]</c>) are left out.
	/// </summary>
	public static string Describe( CompiledShader shader, string shaderName )
	{
		var layout = shader.Material;
		var s = new StringBuilder();
		s.Append( DescriptionHeader ).Append( '\n' );
		s.Append( "type\t" ).Append( layout.Type ).Append( '\n' );
		s.Append( "shader\t" ).Append( shaderName.Replace( '\\', '/' ) ).Append( '\n' );
		s.Append( "file\t" ).Append( Path.GetFileName( shader.Path ) ).Append( '\n' );
		foreach ( var field in layout.Fields )
		{
			if ( field.ShaderNames is not null ) continue;
			var kind = field.Kind switch
			{
				MaterialFieldKind.Float => "float",
				MaterialFieldKind.Int => "int",
				MaterialFieldKind.UInt => "uint",
				MaterialFieldKind.Bool => "bool",
				_ => "texture",
			};

			s.Append( "field\t" ).Append( field.Name )
				.Append( '\t' ).Append( field.Source ?? field.Name )
				.Append( '\t' ).Append( kind )
				.Append( '\t' ).Append( field.Components.ToString( CultureInfo.InvariantCulture ) )
				.Append( '\t' ).Append( field.IsTexture || field.Default is null ? "" : string.Join( ",", field.Default.Select( v => v.ToString( "R", CultureInfo.InvariantCulture ) ) ) )
				.Append( '\t' ).Append( (field.Group ?? "").Replace( '\t', ' ' ).Replace( '\n', ' ' ) )
				.Append( '\t' ).Append( field.Min is { } min ? min.ToString( "R", CultureInfo.InvariantCulture ) : "" )
				.Append( '\t' ).Append( field.Max is { } max ? max.ToString( "R", CultureInfo.InvariantCulture ) : "" )
				.Append( '\t' ).Append( field.Srgb ? "srgb" : "" )
				.Append( '\n' );
		}

		return s.ToString();
	}

	/// <summary>A fingerprint of a layout (field names, kinds, sizes, offsets), which the class and the compiled shader must share.</summary>
	public static uint Hash( MaterialLayout layout )
	{
		var hash = 2166136261u;
		void Add( string text )
		{
			foreach ( var c in text )
			{
				hash ^= c;
				hash *= 16777619u;
			}
		}

		Add( layout.Type );
		foreach ( var f in layout.Fields ) Add( $";{f.Name}:{f.Kind}:{f.Components}@{f.Offset}" );

		// The render state too: a class generated before its struct's attributes changed would resolve the old state
		var states = layout.States();
		if ( states.Fields.Count > 0 || states.Defaults != SurfaceRenderDefaults.None ) Add( $";state:{states}" );
		return hash;
	}

	static (string Type, string Get, string Set) Accessors( MaterialField field )
	{
		var o = field.Offset.ToString( CultureInfo.InvariantCulture );
		// A cube field takes only a cube: a 2D view read as a cube is a descriptor of the wrong kind
		if ( field.Kind == MaterialFieldKind.TextureCube )
			return ("global::Borealis.GpuTexture", $"GetTexture( {o} )", $"SetTexture( {o}, value is null || (value.IsCube && !value.IsArray) ? value : throw new global::System.ArgumentException( \"{field.Name} is a cube texture\" ), srgb: {(field.Srgb ? "true" : "false")} )");
		if ( field.IsTexture )
			return ("global::Borealis.GpuTexture", $"GetTexture( {o} )", $"SetTexture( {o}, value, srgb: {(field.Srgb ? "true" : "false")} )");

		return (field.Kind, field.Components) switch
		{
			(MaterialFieldKind.Float, 1 ) => ("float", $"GetFloat( {o} )", $"SetFloat( {o}, value )"),
			(MaterialFieldKind.Float, 2 ) => ("global::Vector2", $"GetVector2( {o} )", $"SetVector2( {o}, value )"),
			(MaterialFieldKind.Float, 3 ) => ("global::Vector3", $"GetVector3( {o} )", $"SetVector3( {o}, value )"),
			(MaterialFieldKind.Float, 4 ) => ("global::Vector4", $"GetVector4( {o} )", $"SetVector4( {o}, value )"),
			(MaterialFieldKind.Int, 1 ) => ("int", $"GetInt( {o} )", $"SetInt( {o}, value )"),
			(MaterialFieldKind.UInt, 1 ) => ("uint", $"(uint)GetInt( {o} )", $"SetInt( {o}, (int)value )"),
			(MaterialFieldKind.Bool, 1 ) => ("bool", $"GetInt( {o} ) != 0", $"SetInt( {o}, value ? 1 : 0 )"),
			_ => throw new NotSupportedException( $"{field.Name}: {field.Kind}{field.Components} fields have no C# type yet" ),
		};
	}

	/// <summary>A render-state layout as a C# expression.</summary>
	static string StatesLiteral( SurfaceStateLayout states )
	{
		const string ns = "global::Sandbox.ShaderCompiler.";
		var d = states.Defaults;
		static string Bool( bool b ) => b ? "true" : "false";
		var defaults = $"new {ns}SurfaceRenderDefaults( {ns}SurfaceBlend.{d.Blend}, {(d.DepthWrite is { } w ? Bool( w ) : "null")}, {Bool( d.DepthTest )}, {Number( d.DepthBias )}, {Number( d.SlopeDepthBias )}, {Bool( d.TwoSided )}, {Bool( d.AlphaTest )}{(d.Translucent ? ", true" : "")} )";
		var fields = states.Fields.Select( f => $"new {ns}SurfaceStateField( new {ns}SurfaceStateRule( {ns}SurfaceStateKind.{f.Rule.State}, {(f.Rule.Values is null ? "null" : $"[{string.Join( ", ", f.Rule.Values )}]")} ), {f.Offset}, {Bool( f.Float )} )" );
		return $"new( {defaults}, [{string.Join( ", ", fields )}] )";
	}

	static string Literal( MaterialField field, float[] value )
	{
		string At( int i ) => Number( i < value.Length ? value[i] : 0 );
		return (field.Kind, field.Components) switch
		{
			(MaterialFieldKind.Float, 1 ) => At( 0 ),
			(MaterialFieldKind.Float, 2 ) => $"new global::Vector2( {At( 0 )}, {At( 1 )} )",
			(MaterialFieldKind.Float, 3 ) => $"new global::Vector3( {At( 0 )}, {At( 1 )}, {At( 2 )} )",
			(MaterialFieldKind.Float, 4 ) => $"new global::Vector4( {At( 0 )}, {At( 1 )}, {At( 2 )}, {At( 3 )} )",
			(MaterialFieldKind.Bool, _ ) => value.Length > 0 && value[0] != 0 ? "true" : "false",
			(MaterialFieldKind.UInt, _ ) => $"{(uint)MathF.Max( 0, value.Length > 0 ? value[0] : 0 )}u",
			_ => ((int)(value.Length > 0 ? value[0] : 0)).ToString( CultureInfo.InvariantCulture ),
		};
	}

	static string Number( float value )
	{
		var text = value.ToString( "R", CultureInfo.InvariantCulture );
		return (text.Contains( '.' ) || text.Contains( 'E' ) ? text : text + ".0") + "f";
	}
}
